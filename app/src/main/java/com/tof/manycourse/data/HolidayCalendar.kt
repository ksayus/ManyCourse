package com.tof.manycourse.data

import java.time.LocalDate

/**
 * 一天在「法定节假日安排」里的性质。
 *
 * 只有两种，因为**国务院办公厅的通知只说了这两件事**：
 * 哪些日子放假、哪些日子（原本是周末）要上班。至于"调休那天补哪一天的课"，
 * 通知里没有，各校的通知里才有 —— 所以本项目不猜（见 [HolidayCalendar] 的说明）。
 */
enum class HolidayKind {
    /** 法定放假：这天不上课，课表要滤空 */
    Rest,

    /** 调休上班：本来是周末，被调成工作日 —— **照常上课**，只是把日子标出来 */
    Work,
}

/**
 * 某一天的节假日身份（放假 / 调休上班），带节日名。
 *
 * @param name 节日名，如「中秋节」「国庆节」；2025 年的国庆与中秋连放，名字是「国庆节·中秋节」
 */
data class HolidayDay(
    val date: LocalDate,
    val kind: HolidayKind,
    val name: String,
) {
    /** 这一天是不是放假（课表要滤空的那一种）*/
    val isRest: Boolean get() = kind == HolidayKind.Rest

    /** 一行文案：`中秋节放假` / `国庆节调休上班` */
    val label: String get() = if (isRest) "${name}放假" else "${name}调休上班"
}

/**
 * 一条节假日区间（来自通知里的一句话，如「春节：2月15日至23日放假调休，共9天」）。
 *
 * [start]～[end] 是**闭区间**；`start == end` 表示就一天（如「1月4日上班」）。
 *
 * 表里刻意留着"整段"而不是逐个日期摊平：摊平之后就没法对着通知原文核对"这一段
 * 到底是不是 9 天"了，而单测 `HolidayCalendarTest` 正是拿天数去对通知的。
 */
internal data class HolidaySpan(
    val name: String,
    val kind: HolidayKind,
    val start: LocalDate,
    val end: LocalDate,
) {
    /** 这段有几天（闭区间）*/
    val days: Int get() = (end.toEpochDay() - start.toEpochDay()).toInt() + 1

    /** 展示用：`2026-02-15 ~ 2026-02-23` */
    val range: String get() = if (start == end) "$start" else "$start ~ $end"
}

/** 一条放假区间；[to] 省略就是一天。返回 List 是为了和 [work] 一起写进同一张表里 */
private fun rest(name: String, from: String, to: String = from) =
    listOf(HolidaySpan(name, HolidayKind.Rest, LocalDate.parse(from), LocalDate.parse(to)))

/** 一条「调休上班」（通知里那句"X月X日（周X）上班"）；可以一次给好几天 */
private fun work(name: String, vararg days: String): List<HolidaySpan> =
    days.map { HolidaySpan(name, HolidayKind.Work, LocalDate.parse(it), LocalDate.parse(it)) }

/**
 * **法定节假日表**：把"哪天放假、哪天调休上班"做成一个可查询的表，
 * 让课表**自动把放假那天的课置灰**（课照旧列出，但一门都不点亮 —— 见 `CourseEntries.dayIsLit`）。
 *
 * ## 为什么是内置表，而不是联网查接口
 *
 *  - 节假日是**一年一次、国务院办公厅发文定死**的事实（每年 11 月发下一年的安排），
 *    不是每天都在变的实时数据 —— 联网查等于为了一个常量引入一个可能挂掉的服务；
 *  - 本项目其余部分的规矩是"**拿不到权威数据就别编**"（校区坐标要先核实、
 *    作息拿不到就整块停用）。节假日这里同样：宁可只认已发文的那两年，
 *    也不拿"一般是 10 月 1 日放假"去猜没发文的年份；
 *  - 断网、教务系统挂了的时候，过滤节假日本来就该照常工作 ——
 *    它和"课表从哪来"没有关系。
 *
 * ## 数据来源（原文照抄，不加工）
 *
 * | 年份 | 文件 |
 * |---|---|
 * | 2025 | 国务院办公厅关于2025年部分节假日安排的通知（2024-11-12，新华社受权发布） |
 * | 2026 | 国务院办公厅关于2026年部分节假日安排的通知（2025-11-04，新华社受权发布） |
 *
 * 每条区间后面都标了通知里的原话（几天、周几），单测 `HolidayCalendarTest` 会**逐条**
 * 拿天数与星期去核对 —— 这套数据一旦抄错，表现是"某一天课表凭空少了一天的课"，
 * 不会崩也不会报错，只能靠单测钉住。
 *
 * ## 只做"置灰"，不做"补课"
 *
 * 调休上班的日子（如 2026-09-20 周日、2026-10-10 周六）通知里只说了"上班"，
 * **没说补哪一天的课**。各校通知里才有（"10月10日按10月9日（周五）课表上课"），
 * 而且各校口径不一。所以这里：
 *
 *  - 放假 → 那天的课**照旧列出、但不点亮**（灰着；见 `CourseEntries.dayIsLit`）——
 *    这是通知说得清的部分。**刻意不把课删掉**：删了页面就没东西可画，
 *    用户看到的是"课表空了"，分不清是放假、同步挂了、还是自己没选课；
 *  - 调休上班 → **课表一个字不动**，只把这一天标成「调休上班」，让用户自己知道
 *    为什么周六会有课 / 为什么这天要留意学校通知。
 *
 * 不猜补课日的另一个原因：猜错的代价是**凭空造出一门那天不上的课**，
 * 而少标一个"调休"顶多是少一句提示 —— 两者不对等。
 *
 * ## 年份没覆盖怎么办
 *
 * [covers] 返回 false 的年份**一律不置灰**（照常点亮、与平时一样），页面上的说明条也会
 * 如实说"当年节假日数据尚未收录"。加下一年只需在 [spans] 里加一组 [rest] / [work]，
 * 别处一行都不用改。
 */
object HolidayCalendar {

    /**
     * 内置的节假日区间表（按年份分段，逐年追加）。
     *
     * ★ **加新一年的数据就把新的一段贴在最下面**，并在注释里写上通知的发布日期。
     * 顺序不影响结果（[table] 是逐个日期铺出来的），但按年份排着好核对。
     */
    internal val spans: List<HolidaySpan> = listOf(
        // ══════════════ 2025 年（国务院办公厅 2024-11-12 通知 全文照抄）══════════════
        // 一、元旦：1月1日（周三）放假1天，不调休。
        rest("元旦", "2025-01-01"),
        // 二、春节：1月28日（农历除夕、周二）至2月4日（农历正月初七、周二）放假调休，共8天。
        //           1月26日（周日）、2月8日（周六）上班。
        rest("春节", "2025-01-28", "2025-02-04"),
        work("春节", "2025-01-26", "2025-02-08"),
        // 三、清明节：4月4日（周五）至6日（周日）放假，共3天。
        rest("清明节", "2025-04-04", "2025-04-06"),
        // 四、劳动节：5月1日（周四）至5日（周一）放假调休，共5天。4月27日（周日）上班。
        rest("劳动节", "2025-05-01", "2025-05-05"),
        work("劳动节", "2025-04-27"),
        // 五、端午节：5月31日（周六）至6月2日（周一）放假，共3天。
        rest("端午节", "2025-05-31", "2025-06-02"),
        // 六、国庆节、中秋节：10月1日（周三）至8日（周三）放假调休，共8天。
        //                    9月28日（周日）、10月11日（周六）上班。
        rest("国庆节·中秋节", "2025-10-01", "2025-10-08"),
        work("国庆节", "2025-09-28", "2025-10-11"),

        // ══════════════ 2026 年（国务院办公厅 2025-11-04 通知 全文照抄）══════════════
        // 一、元旦：1月1日（周四）至3日（周六）放假调休，共3天。1月4日（周日）上班。
        rest("元旦", "2026-01-01", "2026-01-03"),
        work("元旦", "2026-01-04"),
        // 二、春节：2月15日（农历腊月二十八、周日）至23日（农历正月初七、周一）放假调休，共9天。
        //           2月14日（周六）、2月28日（周六）上班。
        rest("春节", "2026-02-15", "2026-02-23"),
        work("春节", "2026-02-14", "2026-02-28"),
        // 三、清明节：4月4日（周六）至6日（周一）放假，共3天。
        rest("清明节", "2026-04-04", "2026-04-06"),
        // 四、劳动节：5月1日（周五）至5日（周二）放假调休，共5天。5月9日（周六）上班。
        rest("劳动节", "2026-05-01", "2026-05-05"),
        work("劳动节", "2026-05-09"),
        // 五、端午节：6月19日（周五）至21日（周日）放假，共3天。
        rest("端午节", "2026-06-19", "2026-06-21"),
        // 六、中秋节：9月25日（周五）至27日（周日）放假，共3天。
        rest("中秋节", "2026-09-25", "2026-09-27"),
        // 七、国庆节：10月1日（周四）至7日（周三）放假调休，共7天。
        //            9月20日（周日）、10月10日（周六）上班。
        rest("国庆节", "2026-10-01", "2026-10-07"),
        work("国庆节", "2026-09-20", "2026-10-10"),
    ).flatten()

    /**
     * 已收录的年份（升序）—— 页面上"当年数据还没收录"的提示要用它。
     *
     * 从 [spans] 现算而不是写死一个常量：写死的话加完新一年忘了改它，
     * 功能会静默不生效（而且没人看得出来）。
     */
    internal val years: List<Int> get() = spans.map { it.start.year }.distinct().sorted()

    /** 日期 → 那天的节假日身份；逐个日期铺出来，查表是 O(1) */
    private val table: Map<LocalDate, HolidayDay> by lazy { expandHolidaySpans(spans) }

    /**
     * 这一天是不是**放假**（课表要滤空的日子）。
     *
     * 未收录的年份一律返回 false（不过滤）—— 这一点和 [of] 的"返回 null"是同一件事，
     * 只是给调用方省一次判空。
     */
    fun isRestDay(date: LocalDate): Boolean = of(date)?.isRest == true

    /** 这一天的节假日身份；不是节假日、或这一年的数据还没收录时返回 null */
    fun of(date: LocalDate): HolidayDay? = table[date]

    /** 这一年在内置表里吗（false = 那年的课表不过滤，页面上会如实说明）*/
    fun covers(year: Int): Boolean = year in years

    /** 内置表覆盖的年份区间文案：`2025-2026`；一天都没有时是空串 */
    val coverageLabel: String
        get() = years.let { if (it.isEmpty()) "" else "${it.first()}-${it.last()}" }
}

/**
 * 把区间表铺成"日期 → 节假日"的查表（纯函数，可单测）。
 *
 * 同一天被两条区间覆盖时**后者覆盖前者**（`put` 的语义）：真出现这种情况说明表抄错了，
 * 单测 `HolidayCalendarTest` 会直接拦下来，而不是让它在这里悄悄消失。
 *
 * @param spans 区间表；区间顺序不影响已铺好的日期，只影响"重叠时谁赢"
 */
internal fun expandHolidaySpans(spans: List<HolidaySpan>): Map<LocalDate, HolidayDay> {
    val table = mutableMapOf<LocalDate, HolidayDay>()
    spans.forEach { span ->
        var date = span.start
        while (!date.isAfter(span.end)) {
            table[date] = HolidayDay(date = date, kind = span.kind, name = span.name)
            date = date.plusDays(1)
        }
    }
    return table
}
